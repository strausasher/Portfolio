// Regenerate src/app/components/imageDimensions.ts from the project's image trees.
//
//   node scripts/gen-image-dimensions.mjs
//
// Run this after adding or optimizing images. The generated map lets <img> tags
// carry width/height attributes, which reserves layout space before the file
// loads. The masonry gallery depends on it: react-responsive-masonry only
// balances its columns once every tile reports a non-zero height, so without
// intrinsic sizes it falls back to an unbalanced round-robin layout that leaves
// visible gaps at the bottom of the shorter columns.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(ROOT, 'src/app/components/imageDimensions.ts');

// Only images actually imported by a component are worth including — importing an
// unused one here would drag it into the bundle.
const sourceFiles = [];
(function walkSrc(dir) {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, e.name);
    if (e.isDirectory()) walkSrc(full);
    else if (/\.tsx?$/.test(e.name) && full !== OUT) sourceFiles.push(full);
  }
})(path.join(ROOT, 'src'));

const code = sourceFiles.map(f => fs.readFileSync(f, 'utf8')).join('\n');
// Strip comments so commented-out imports don't count as usage.
const live = code.replace(/\/\*[\s\S]*?\*\//g, '').replace(/^\s*\/\/.*$/gm, '');

function* walk(dir, base) {
  if (!fs.existsSync(dir)) return;
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, e.name);
    if (e.isDirectory()) yield* walk(full, base);
    else if (e.name.endsWith('.webp')) yield full;
  }
}

const entries = [];
for (const [dir, specifier] of [
  // figma:asset/<file> resolves to src/assets/<file> (see vite.config.ts)
  ['src/assets', f => `figma:asset/${path.basename(f)}`],
  // imported by path relative to src/app/components/
  ['src/imports', f => `../../imports/${path.relative(path.join(ROOT, 'src/imports'), f).split(path.sep).join('/')}`],
]) {
  for (const full of walk(path.join(ROOT, dir))) {
    const spec = specifier(full);
    // Bulk sets pulled in via import.meta.glob (e.g. sketchbook-*.webp in
    // Gallery.tsx) never appear as a literal specifier string, so match by
    // filename prefix instead of requiring an exact `live.includes` hit.
    const bulkImported = /^sketchbook-/.test(path.basename(full)) && live.includes("'../../assets/sketchbook-*.webp'");
    if (!bulkImported && !live.includes(spec)) continue;
    const { width, height } = await sharp(full).metadata();
    entries.push({ spec, width, height });
  }
}

entries.sort((a, b) => a.spec.localeCompare(b.spec));

const imports = entries.map((e, i) => `import a${i} from '${e.spec}';`);
const map = entries.map((e, i) => `  [a${i}]: [${e.width}, ${e.height}],`);

fs.writeFileSync(OUT, `// AUTO-GENERATED by scripts/gen-image-dimensions.mjs - do not edit by hand.
// Maps each bundled image URL to its intrinsic [width, height] so <img> tags can
// reserve the right space before the file loads.

${imports.join('\n')}

export const imageDimensions: Record<string, [number, number]> = {
${map.join('\n')}
};

/** width/height attrs for an image URL, or {} if it is not a bundled asset. */
export function dimsFor(src: string): { width?: number; height?: number } {
  const d = imageDimensions[src];
  return d ? { width: d[0], height: d[1] } : {};
}
`);

console.log(`wrote ${entries.length} entries to ${path.relative(ROOT, OUT)}`);
